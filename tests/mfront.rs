//! Loads and integrates the behaviours of `tests/behaviours`, compiled by
//! `mfront` when the tests start. Without `mfront` in the `PATH`, the tests
//! fail: they never pass without checking anything.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::OnceLock;

use rustfront::voigt::{self, Shear};
use rustfront::{
    Behaviour, Error, FinalState, FiniteStrainTangentOperator, Frame, Hypothesis, InitialState,
    MaterialProperty, OutOfBoundsPolicy, ParameterValue, Rotation, Settings, StressMeasure,
    Symmetry, TangentOperator, TimeStep, VariableType,
};

const YOUNG: f64 = 200e9;
const POISSON: f64 = 0.3;
const LAMBDA: f64 = YOUNG * POISSON / ((1.0 + POISSON) * (1.0 - 2.0 * POISSON));
const MU: f64 = YOUNG / (2.0 * (1.0 + POISSON));
const TEMPERATURE: [f64; 1] = [293.15];

/// The library `name` (`Behaviour` for the behaviours and models,
/// `GenericMaterialLaw` for the material properties), compiled by `mfront`,
/// once for all the tests, from every source of `tests/behaviours`.
fn library(name: &str) -> PathBuf {
    static DIRECTORY: OnceLock<PathBuf> = OnceLock::new();
    let directory = DIRECTORY.get_or_init(|| {
        let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("behaviours");
        std::fs::create_dir_all(&dir).unwrap();
        let sources = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/behaviours");
        let sources = std::fs::read_dir(sources)
            .unwrap()
            .map(|entry| entry.unwrap().path())
            .filter(|path| path.extension().is_some_and(|e| e == "mfront"));
        let output = Command::new("mfront")
            .args(["--obuild", "--interface=generic"])
            .args(sources)
            .current_dir(&dir)
            .output()
            .unwrap_or_else(|e| {
                panic!(
                    "cannot run `mfront` ({e}): these tests need MFront (TFEL ≥ 5.1.0) in the PATH"
                )
            });
        assert!(
            output.status.success(),
            "mfront failed:\n{}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        dir.join("src")
    });
    let (prefix, suffix) = (std::env::consts::DLL_PREFIX, std::env::consts::DLL_SUFFIX);
    directory.join(format!("{prefix}{name}{suffix}"))
}

/// Loads the behaviour or model `name`.
fn load(name: &str, hypothesis: Hypothesis, settings: &Settings) -> Result<Behaviour, Error> {
    // SAFETY: the library was just generated by MFront.
    unsafe { Behaviour::load(library("Behaviour"), name, hypothesis, settings) }
}

/// Integrates `Elasticity` in 3D from rest to the strain `eps` (TFEL
/// convention): the stress, the von Mises stress and the tangent operator.
fn elastic(eps: [f64; 6]) -> ([f64; 6], f64, Vec<f64>) {
    let behaviour = load(
        "Elasticity",
        Hypothesis::Tridimensional,
        &Settings::default(),
    )
    .unwrap();
    let material = [YOUNG, POISSON];
    let (isv0, mut isv1) = ([0.0], [0.0]);
    let (zero, mut sig) = ([0.0; 6], [0.0; 6]);
    let mut k = vec![0.0; 36];
    let s0 = InitialState {
        gradients: &zero,
        thermodynamic_forces: &zero,
        material_properties: &material,
        internal_state_variables: &isv0,
        external_state_variables: &TEMPERATURE,
        ..Default::default()
    };
    let mut s1 = FinalState {
        gradients: &eps,
        thermodynamic_forces: &mut sig,
        material_properties: &material,
        internal_state_variables: &mut isv1,
        external_state_variables: &TEMPERATURE,
    };
    let tangent = Some((TangentOperator::ConsistentTangent, k.as_mut_slice()));
    let r = behaviour
        .integrate(
            TimeStep {
                dt: 0.0,
                max_scaling_factor: 1.0,
            },
            &s0,
            &mut s1,
            tangent,
        )
        .unwrap();
    assert_eq!(r.time_step_scaling_factor, 1.0);
    (sig, isv1[0], k)
}

fn assert_close(found: f64, expected: f64) {
    let tolerance = 1e-12 * expected.abs().max(1.0);
    assert!(
        (found - expected).abs() <= tolerance,
        "found {found}, expected {expected}"
    );
}

#[test]
fn elasticity_describes_itself() {
    let behaviour = load(
        "Elasticity",
        Hypothesis::Tridimensional,
        &Settings::default(),
    )
    .unwrap();
    let d = behaviour.description();
    assert_eq!(d.name, "Elasticity");
    assert_eq!(d.hypothesis, Hypothesis::Tridimensional);
    // The version of the `mfront` that compiled the library: `Version : 5.1.0`.
    let output = Command::new("mfront").arg("--version").output().unwrap();
    let version = String::from_utf8_lossy(&output.stdout);
    assert!(
        version.contains(&format!("Version : {}", d.tfel_version)),
        "{} is not the version of mfront: {version}",
        d.tfel_version
    );
    assert_eq!(d.symmetry, Symmetry::Isotropic);
    let names =
        |v: &rustfront::Variables| v.list.iter().map(|v| v.name.clone()).collect::<Vec<_>>();
    assert_eq!(names(&d.gradients), ["Strain"]);
    assert_eq!(d.gradients.list[0].variable_type, VariableType::Stensor);
    assert_eq!(d.gradients.size, 6);
    assert_eq!(names(&d.thermodynamic_forces), ["Stress"]);
    assert_eq!(
        names(&d.material_properties),
        ["YoungModulus", "PoissonRatio"]
    );
    assert_eq!(names(&d.internal_state_variables), ["VonMisesStress"]);
    assert_eq!(names(&d.external_state_variables), ["Temperature"]);
    assert_eq!(
        d.tangent_operator_blocks,
        [("Stress".to_owned(), "Strain".to_owned())]
    );
    assert_eq!(d.tangent_operator_size, 36);
}


//! `mtest-rs`: tests an MFront behaviour at one material point, reading the
//! same `.mtest` files as MTest and writing the same `.res` files.
//!
//! An unofficial, independent reimplementation in Rust of a subset of MTest,
//! which is part of TFEL, built on rustfront. Not affiliated with the TFEL
//! project, CEA or EDF.
//!
//! ```text
//! mtest-rs <file.mtest> [--output <file.res>]
//! ```

mod expression;
mod input;
mod simulation;

use std::path::Path;
use std::process::ExitCode;

use rustfront::{Behaviour, MaterialProperty, OutOfBoundsPolicy, Settings, VariableType};

fn main() -> ExitCode {
    let arguments: Vec<String> = std::env::args().skip(1).collect();
    let (file, output) = match arguments.as_slice() {
        [file] => (file, None),
        [file, flag, output] if flag == "--output" => (file, Some(output.clone())),
        _ => {
            eprintln!("usage: mtest-rs <file.mtest> [--output <file.res>]");
            return ExitCode::from(2);
        }
    };
    // Everything that can fail, its error printed below.
    let outcome = (|| -> Result<String, String> {
        let source =
            std::fs::read_to_string(file).map_err(|e| format!("cannot read `{file}`: {e}"))?;
        let test = input::parse(&source).map_err(|e| format!("{file}: {e}"))?;
        let parameters: Vec<_> = test
            .parameters
            .iter()
            .map(|(n, v)| (n.as_str(), *v))
            .collect();
        let settings = Settings {
            parameters: &parameters,
            out_of_bounds_policy: test.out_of_bounds_policy,
            stress_measure: test.stress_measure,
            finite_strain_tangent_operator: test.finite_strain_tangent_operator,
        };
        // SAFETY: like MTest, mtest-rs loads the library the file names, which
        // must have been generated by MFront; nothing else runs meanwhile.
        let behaviour =
            unsafe { Behaviour::load(&test.library, &test.behaviour, test.hypothesis, &settings) }
                .map_err(|e| e.to_string())?;
        let mut laws = Vec::new();
        for (name, library, law) in &test.material_property_laws {
            // SAFETY: as for the behaviour.
            let property =
                unsafe { MaterialProperty::load(library, law, &[], OutOfBoundsPolicy::None) }
                    .map_err(|e| e.to_string())?;
            laws.push((name.clone(), property));
        }
        let rows = simulation::run(&test, &behaviour, &laws)?;

        // The columns, described as MTest does.
        let d = behaviour.description();
        let suffixes = simulation::stensor_suffixes(test.hypothesis);
        let mut text = String::from("# first column: time\n");
        let mut column = 2;
        // The strain and the stress, or the deformation gradient and the
        // Cauchy stress; nothing for a point-wise model.
        let tensors = match d.gradients.list.first().map(|g| g.variable_type) {
            None => vec![],
            Some(VariableType::Tensor) => vec![
                (
                    "F",
                    "deformation gradient",
                    simulation::tensor_suffixes(test.hypothesis),
                ),
                ("S", "Cauchy stress", suffixes),
            ],
            Some(_) => vec![("E", "strain", suffixes), ("S", "stress", suffixes)],
        };
        for (prefix, quantity, suffixes) in tensors {
            for (i, suffix) in suffixes.iter().enumerate() {
                text += &format!(
                    "# {column} column: {}th component of the {quantity} ({prefix}{suffix})\n",
                    i + 1
                );
                column += 1;
            }
        }
        let ordinals = [
            "first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth", "ninth",
        ];
        for v in &d.internal_state_variables.list {
            if v.size == 1 {
                text += &format!("# {column} column: {}\n", v.name);
                column += 1;
                continue;
            }
            for j in 0..v.size {
                let component = match v.variable_type {
                    VariableType::Stensor => format!("{}{}", v.name, suffixes[j]),
                    _ => format!("{}{}", v.name, j + 1),
                };
                text += &format!(
                    "# {column} column: {} component of internal variable '{}' ({component})\n",
                    ordinals[j], v.name
                );
                column += 1;
            }
        }
        text += &format!("# {column} column: stored energy\n");
        text += &format!("# {} column: dissipated energy\n", column + 1);
        let digits = test.output_precision - 1;
        for row in rows {
            let values: Vec<String> = row.iter().map(|v| format!("{v:.digits$e}")).collect();
            text += &values.join(" ");
            text.push('\n');
        }

        // Like MTest, `<name>.res` in the current directory by default.
        let stem = Path::new(file)
            .file_stem()
            .map_or("mtest", |s| s.to_str().unwrap_or("mtest"));
        let path = output
            .or(test.output_file)
            .unwrap_or_else(|| format!("{stem}.res"));
        std::fs::write(&path, text).map_err(|e| format!("cannot write `{path}`: {e}"))?;
        Ok(path)
    })();
    match outcome {
        Ok(path) => {
            println!("results written to `{path}`");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("mtest-rs: {e}");
            ExitCode::FAILURE
        }
    }
}
